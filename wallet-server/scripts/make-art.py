#!/usr/bin/env python3
"""Writes src/art.js: the card's logo and its prayer rings, drawn from the app icon.

- The logo is the icon's crescent and star on a clear background, so it sits on the card's
  green without the icon's square around it.
- Each ring has five segments, one per prayer from Fajr at the top, clockwise; a logged prayer's
  segment is gold. There is one ring per combination ("10110" = Fajr, Asr and Maghrib logged), as
  the card's thumbnail.

Run from wallet-server/ after the app icon changes (needs Pillow): python3 scripts/make-art.py
"""
import base64
import io
import math
from pathlib import Path

from PIL import Image, ImageDraw

ICON = Path('../apple/Azkar/Assets.xcassets/AppIcon.appiconset/AppIcon.png')
OUT = Path('src/art.js')
GREEN = (14, 107, 84)
CREAM = (245, 232, 204)
GOLD = (217, 178, 95)


def glyph() -> Image.Image:
    """The crescent and star, unmixed from the icon's green: each pixel's colour and coverage."""
    icon = Image.open(ICON).convert('RGB')
    out = Image.new('RGBA', icon.size)
    src, dst = icon.load(), out.load()
    for y in range(icon.height):
        for x in range(icon.width):
            p = src[x, y]
            best = None
            for f in (CREAM, GOLD):
                d = [f[i] - GREEN[i] for i in range(3)]
                v = [p[i] - GREEN[i] for i in range(3)]
                a = max(0.0, min(1.0, sum(v[i] * d[i] for i in range(3)) / sum(c * c for c in d)))
                miss = sum((GREEN[i] + a * d[i] - p[i]) ** 2 for i in range(3))
                if best is None or miss < best[0]:
                    best = (miss, f, a)
            _, f, a = best
            dst[x, y] = (*f, round(a * 255))
    # The drawing spans x 218-822, y 202-840 of the 1024 icon: a square around it.
    side = 680
    cx, cy = (218 + 822) // 2, (202 + 840) // 2
    return out.crop((cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2))


def ring(mask: str, size: int, art: Image.Image) -> Image.Image:
    over = 4
    big = size * over
    image = Image.new('RGBA', (big, big))
    draw = ImageDraw.Draw(image)
    width = round(big * 0.085)
    inset = width // 2 + round(big * 0.03)
    box = (inset, inset, big - inset, big - inset)
    gap = 14  # degrees between segments
    for i, logged in enumerate(mask):
        start = -90 + i * 72 + gap / 2
        end = start + 72 - gap
        colour = (*GOLD, 255) if logged == '1' else (*CREAM, 70)
        draw.arc(box, start, end, fill=colour, width=width)
        # Round ends.
        r = (big - 2 * inset) / 2
        for angle in (start, end):
            t = math.radians(angle)
            x = big / 2 + (r - width / 2) * math.cos(t)
            y = big / 2 + (r - width / 2) * math.sin(t)
            draw.ellipse((x - width / 2, y - width / 2, x + width / 2, y + width / 2), fill=colour)
    inner = round(big * 0.46)
    centre = art.resize((inner, inner), Image.LANCZOS)
    image.alpha_composite(centre, ((big - inner) // 2, (big - inner) // 2))
    return image.resize((size, size), Image.LANCZOS)


def png(image: Image.Image) -> str:
    buffer = io.BytesIO()
    # A small palette keeps the server small; the art has three colours and their edges.
    image.quantize(colors=48, method=Image.Quantize.FASTOCTREE).save(buffer, 'PNG', optimize=True)
    return base64.b64encode(buffer.getvalue()).decode()


def main() -> None:
    art = glyph()
    lines = [
        '// Generated by scripts/make-art.py from the app icon. Do not edit.',
        '',
        '/** The crescent and star, for the top of the card. */',
        'export const LOGO = {',
    ]
    for name, side in (('logo.png', 50), ('logo@2x.png', 100), ('logo@3x.png', 150)):
        lines.append(f"  '{name}': '{png(art.resize((side, side), Image.LANCZOS))}',")
    lines += [
        '}',
        '',
        '/** The thumbnail for each set of logged prayers, Fajr first: "10110" -> { 2x, 3x }. */',
        'export const RINGS = {',
    ]
    for n in range(32):
        mask = format(n, '05b')
        lines.append(f"  '{mask}': ['{png(ring(mask, 180, art))}', '{png(ring(mask, 270, art))}'],")
    lines += ['}', '']
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT} ({OUT.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
