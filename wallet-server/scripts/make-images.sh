#!/bin/zsh
# Writes src/images.js: the card's icon and logo, made from the app icon, as base64.
# Run from wallet-server/ after the app icon changes.
set -e
ICON=../apple/Azkar/Assets.xcassets/AppIcon.appiconset/AppIcon.png
T=$(mktemp -d)
for s in 29 58 87 50 100 150; do sips -z $s $s $ICON --out $T/i$s.png >/dev/null; done
{
  echo "// Generated by scripts/make-images.sh from the app icon. Do not edit."
  echo "export const IMAGES = {"
  echo "  'icon.png': '$(base64 -i $T/i29.png)',"
  echo "  'icon@2x.png': '$(base64 -i $T/i58.png)',"
  echo "  'icon@3x.png': '$(base64 -i $T/i87.png)',"
  echo "  'logo.png': '$(base64 -i $T/i50.png)',"
  echo "  'logo@2x.png': '$(base64 -i $T/i100.png)',"
  echo "  'logo@3x.png': '$(base64 -i $T/i150.png)',"
  echo "}"
} > src/images.js
rm -rf $T
